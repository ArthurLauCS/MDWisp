/** Exercise the sidebar divider with real Electron input and an isolated profile. */
const { app, BrowserWindow, dialog } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const assert = require('node:assert/strict')
const OUT = path.resolve(process.argv[2] || 'design-review/sidebar-split')
require('node:fs').mkdirSync(path.join(OUT, 'documents'), { recursive: true })
app.setPath('userData', path.join(OUT, 'profile'))
app.setPath('documents', path.join(OUT, 'documents'))
dialog.showMessageBox = async () => ({ response: 1 })
require(path.resolve(__dirname, '../out/main/index.js'))
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))

async function main() {
  for (let i = 0; i < 80 && !BrowserWindow.getAllWindows().length; i++) await wait(100)
  const win = BrowserWindow.getAllWindows()[0]
  win.webContents.setBackgroundThrottling(false)
  win.setSize(1440, 900)
  const run = code => win.webContents.executeJavaScript(code, true).catch(error => {
    throw new Error(`${code}: ${error.message}`)
  })
  const until = async code => {
    for (let i = 0; i < 80; i++) { if (await run(code)) return; await wait(100) }
    throw new Error(`Timed out: ${code}`)
  }
  const settings = patch => run(`window.__mdview.setSettings(${JSON.stringify(patch)})`)
  const ratio = () => run('window.mdview.settings.get().then(s => s.assetsRatio)')
  const point = () => run(`(() => {
    const r = document.querySelector('.split-resizer').getBoundingClientRect()
    return { x: Math.round(r.left + r.width / 2), y: Math.round(r.top + r.height / 2) }
  })()`)
  const mouse = (type, p) => win.webContents.sendInputEvent({ type, ...p, button: 'left', clickCount: 1,
    modifiers: type !== 'mouseUp' ? ['leftButtonDown'] : [] })
  const drag = async y => {
    const p = await point()
    mouse('mouseDown', p)
    mouse('mouseMove', { x: p.x, y })
    await wait(60)
    mouse('mouseUp', { x: p.x, y })
    await until('!document.documentElement.dataset.resizing')
    await wait(100)
  }
  const shot = async name => {
    await run('document.fonts.ready.then(() => true)')
    await wait(100)
    await fs.writeFile(path.join(OUT, name + '.png'), (await win.webContents.capturePage()).toPNG())
  }
  await until('!!document.querySelector(".cm-content")')
  assert.equal(await run('!!document.querySelector(".split-resizer")'), false, 'draft has no image divider')
  const doc = path.join(OUT, 'documents/sidebar.md')
  await fs.writeFile(doc, '# Sidebar\n\n## First\n\nText.\n\n## Second\n\nMore text.')
  await settings({ sidebarVisible: true, outlineVisible: true, language: 'en', motion: 'off', autoSave: false })
  await run(`window.__mdview.loadDocument(${JSON.stringify(doc)})`)
  await until('!!document.querySelector(".split-resizer")')
  assert.equal(await ratio(), 0.4, 'existing settings default to 40 percent')
  const bounds = await run(`({ top: document.querySelector('.sidebar__head').getBoundingClientRect().bottom,
    bottom: document.querySelector('.sidebar').getBoundingClientRect().bottom })`)
  const middle = Math.round((bounds.top + bounds.bottom) / 2)
  await drag(middle)
  assert.ok(Math.abs((await point()).y - middle) < 10, 'divider tracks the pointer')
  await shot('01-split-dark')
  await drag(Math.round(bounds.top + 10))
  assert.equal(await ratio(), 1)
  assert.equal(await run('document.querySelector(".outline").getBoundingClientRect().height'), 0)
  await shot('02-navigation-collapsed')
  await drag(middle)
  assert.ok(await run('document.querySelector(".outline").getBoundingClientRect().height > 0'))
  await drag(Math.round(bounds.bottom - 10))
  assert.equal(await ratio(), 0)
  assert.equal(await run('document.querySelector(".assets").getBoundingClientRect().height'), 0)
  await shot('03-images-collapsed')
  await drag(middle)
  await run('document.querySelector(".split-resizer").dispatchEvent(new MouseEvent("dblclick", {bubbles:true}))')
  await until('document.querySelector(".split-resizer").getAttribute("aria-valuenow") === "40"')
  await run('document.querySelector(".split-resizer").focus()')
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Up' })
  win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Up' })
  await until('document.querySelector(".split-resizer").getAttribute("aria-valuenow") === "45"')
  assert.equal(await ratio(), 0.45)
  win.reload()
  await until('!!document.querySelector(".split-resizer")')
  assert.equal(await ratio(), 0.45, 'split persists after reload')
  await settings({ theme: 'light', language: 'zh-CN' })
  await shot('04-split-light')
  assert.equal(await run('document.querySelector(".split-resizer").getAttribute("aria-label")'), '调整大纲与图片高度')
  await settings({ outlineVisible: false })
  await drag(Math.round(bounds.top + 10))
  assert.equal(await run('document.querySelector(".sidebar__tree").getBoundingClientRect().height'), 0)
  await drag(middle)
  mouse('mouseDown', await point())
  await until('document.documentElement.dataset.resizing === "row"')
  await settings({ sidebarVisible: false })
  await until('!document.documentElement.dataset.resizing')
  mouse('mouseUp', { x: 100, y: middle })
  await settings({ sidebarVisible: true, outlineVisible: true })
  win.setSize(900, 800)
  await wait(200)
  await settings({ sidebarVisible: true })
  await until('!!document.querySelector(".split-resizer")')
  await shot('05-split-narrow')
  assert.ok(await run('document.querySelector(".split-resizer").getBoundingClientRect().height > 0'))
  console.log('PASS: sidebar split geometry, collapse/restore, reset, keyboard, persistence, locales, themes, file tree, unmount cleanup and narrow layout')
  app.quit()
}
app.whenReady().then(() => main().catch(error => { console.error(error); app.exit(1) }))
